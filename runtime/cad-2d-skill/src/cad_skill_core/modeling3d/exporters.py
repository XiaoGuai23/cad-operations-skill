def export_binary_stl(mesh: SolidMesh3D, path: Path, *, header_label: str = "cad-operations-skill-3d") -> Path:
    """Write a deterministic IEEE-754 little-endian binary STL file."""

    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    num_tris = int(mesh.faces.shape[0])
    normals = mesh.face_normals.astype("<f4")
    tris = mesh.vertices[mesh.faces].astype("<f4")  # (F, 3, 3)

    stl_dtype = np.dtype(
        [
            ("normal", "<f4", (3,)),
            ("v0", "<f4", (3,)),
            ("v1", "<f4", (3,)),
            ("v2", "<f4", (3,)),
            ("attr", "<u2"),
        ]
    )
    records = np.zeros(num_tris, dtype=stl_dtype)
    records["normal"] = normals
    records["v0"] = tris[:, 0, :]
    records["v1"] = tris[:, 1, :]
    records["v2"] = tris[:, 2, :]
    records["attr"] = 0

    header_bytes = header_label.encode("ascii", errors="ignore")[:80].ljust(80, b"\x00")
    with dest.open("wb") as fh:
        fh.write(header_bytes)
        fh.write(struct.pack("<I", num_tris))
        fh.write(records.tobytes())
    return dest


def export_obj(mesh: SolidMesh3D, path: Path, *, object_name: str = "cad_solid") -> Path:
    """Write a Wavefront OBJ file with shared vertices and per-face normals."""

    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    normals = mesh.face_normals
    lines = [
        "# Generated by cad-operations-skill modeling3d",
        f"o {object_name}",
    ]
    for vx, vy, vz in mesh.vertices:
        lines.append(f"v {vx:.6f} {vy:.6f} {vz:.6f}")
    for nx, ny, nz in normals:
        lines.append(f"vn {nx:.6f} {ny:.6f} {nz:.6f}")
    for f_idx, (i0, i1, i2) in enumerate(mesh.faces, start=1):
        lines.append(f"f {int(i0)+1}//{f_idx} {int(i1)+1}//{f_idx} {int(i2)+1}//{f_idx}")
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return dest


def export_glb(mesh: SolidMesh3D, path: Path, *, name: str = "cad_solid") -> Path:
    """Write a standards-compliant glTF 2.0 binary (.glb) container for web 3D viewers."""

    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True)

    # Expand per-face crisp CAD shading vertices (3 * F) so flat/curved facets render sharply in WebGL
    num_faces = int(mesh.faces.shape[0])
    positions = mesh.vertices[mesh.faces].reshape(-1, 3).astype("<f4")
    face_norms = np.repeat(mesh.face_normals.astype("<f4"), 3, axis=0)
    indices = np.arange(num_faces * 3, dtype="<u4")

    idx_bytes = indices.tobytes()
    pos_bytes = positions.tobytes()
    nrm_bytes = face_norms.tobytes()

    def pad4(b: bytes, fill: bytes = b"\x00") -> bytes:
        rem = len(b) % 4
        return b if rem == 0 else b + fill * (4 - rem)

    idx_padded = pad4(idx_bytes)
    pos_padded = pad4(pos_bytes)
    nrm_padded = pad4(nrm_bytes)
    bin_blob = idx_padded + pos_padded + nrm_padded

    pos_min = [float(v) for v in positions.min(axis=0)]
    pos_max = [float(v) for v in positions.max(axis=0)]

    gltf_json = {
        "asset": {
            "version": "2.0",
            "generator": "cad-operations-skill/modeling3d",
            "extras": {"units": "mm", "coordinate_system": "CAD-Z-up"},
        },
        "scene": 0,
        "scenes": [{"name": name, "nodes": [0]}],
        "nodes": [{"name": name, "mesh": 0}],
        "materials": [
            {
                "name": "EngineeringSteel",
                "doubleSided": False,
                "pbrMetallicRoughness": {
                    "baseColorFactor": [0.72, 0.76, 0.80, 1.0],
                    "metallicFactor": 0.55,
                    "roughnessFactor": 0.38,
                },
            }
        ],
        "meshes": [
            {
                "name": name,
                "primitives": [
                    {
                        "attributes": {"POSITION": 1, "NORMAL": 2},
                        "indices": 0,
                        "material": 0,
                        "mode": 4,  # TRIANGLES
                    }
                ],
            }
        ],
        "buffers": [{"byteLength": len(bin_blob)}],
        "bufferViews": [
            {
                "buffer": 0,
                "byteOffset": 0,
                "byteLength": len(idx_bytes),
                "target": 34963,  # ELEMENT_ARRAY_BUFFER
            },
            {
                "buffer": 0,
                "byteOffset": len(idx_padded),
                "byteLength": len(pos_bytes),
                "target": 34962,  # ARRAY_BUFFER
            },
            {
                "buffer": 0,
                "byteOffset": len(idx_padded) + len(pos_padded),
                "byteLength": len(nrm_bytes),
                "target": 34962,
            },
        ],
        "accessors": [
            {
                "bufferView": 0,
                "byteOffset": 0,
                "componentType": 5125,  # UNSIGNED_INT
                "count": int(indices.shape[0]),
                "type": "SCALAR",
            },
            {
                "bufferView": 1,
                "byteOffset": 0,
                "componentType": 5126,  # FLOAT
                "count": int(positions.shape[0]),
                "type": "VEC3",
                "min": pos_min,
                "max": pos_max,
            },
            {
                "bufferView": 2,
                "byteOffset": 0,
                "componentType": 5126,
                "count": int(face_norms.shape[0]),
                "type": "VEC3",
            },
        ],
    }

    json_bytes = pad4(
        json.dumps(gltf_json, separators=(",", ":"), ensure_ascii=False).encode("utf-8"),
        fill=b" ",
    )
    total_length = 12 + 8 + len(json_bytes) + 8 + len(bin_blob)

    with dest.open("wb") as fh:
        # GLB Header: magic 'glTF' (0x46546C67), version 2, totalLength
        fh.write(struct.pack("<III", 0x46546C67, 2, total_length))
        # Chunk 0: JSON (0x4E4F534A)
        fh.write(struct.pack("<II", len(json_bytes), 0x4E4F534A))
        fh.write(json_bytes)
        # Chunk 1: BIN (0x004E4942)
        fh.write(struct.pack("<II", len(bin_blob), 0x004E4942))
        fh.write(bin_blob)
    return dest


def export_3d_dxf(mesh: SolidMesh3D, path: Path, *, layer: str = "SOLID3D") -> Path:
    """Write an audited R2010 3D DXF containing a manifold SubDMesh/MESH entity."""

    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    doc = ezdxf.new("R2010")
    doc.header["$INSUNITS"] = 4  # mm
    bmin_x, bmin_y, bmin_z, bmax_x, bmax_y, bmax_z = mesh.actual_bbox_mm()
    doc.header["$EXTMIN"] = (bmin_x, bmin_y, bmin_z)
    doc.header["$EXTMAX"] = (bmax_x, bmax_y, bmax_z)
    if layer not in doc.layers:
        doc.layers.add(layer, color=7)

    dxf_mesh = doc.modelspace().add_mesh(dxfattribs={"layer": layer, "subdivision_levels": 0})
    with dxf_mesh.edit_data() as mesh_data:
        mesh_data.vertices = [tuple(float(c) for c in row) for row in mesh.vertices]
        mesh_data.faces = [tuple(int(idx) for idx in row) for row in mesh.faces]

    doc.saveas(dest)
    reopened = ezdxf.readfile(dest)
    auditor = reopened.audit()
    if auditor.has_errors:
        raise RuntimeError(f"3D DXF failed ezdxf audit with {len(auditor.errors)} error(s)")
    return dest


def render_isometric_png(
    mesh: SolidMesh3D,
    path: Path,
    *,
    title: str | None = None,
    width_px: int = 960,
    height_px: int = 720,
    render_lock=None,
) -> Path:
    """Render a deterministic orthographic isometric shaded PNG preview of a SolidMesh3D."""

    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    lock = render_lock if render_lock is not None else _FONT_RENDER_LOCK

    # Standard CAD isometric camera basis (looking from (+1, -1, +0.85) toward origin)
    yaw = -pi / 4.0
    pitch = 35.26438968 * pi / 180.0
    cy, sy = cos(yaw), sin(yaw)
    cp, sp = cos(pitch), sin(pitch)

    # Screen right (+u), screen up (+v), camera depth (+w toward viewer)
    right = np.array([cy, -sy, 0.0], dtype=np.float64)
    up = np.array([-sy * sp, -cy * sp, cp], dtype=np.float64)
    view_dir = np.array([sy * cp, cy * cp, sp], dtype=np.float64)
    view_dir /= np.linalg.norm(view_dir)

    light_key = np.array([0.45, -0.55, 0.70], dtype=np.float64)
    light_key /= np.linalg.norm(light_key)
    light_fill = np.array([-0.60, 0.30, 0.40], dtype=np.float64)
    light_fill /= np.linalg.norm(light_fill)

    verts = mesh.vertices
    proj_u = verts @ right
    proj_v = verts @ up
    proj_w = verts @ view_dir

    faces = mesh.faces
    normals = mesh.face_normals
    # Painter's algorithm depth sort (back-to-front)
    tri_depth = proj_w[faces].mean(axis=1)
    order = np.argsort(tri_depth)

    ordered_faces = faces[order]
    ordered_normals = normals[order]

    polys_2d = np.stack([proj_u[ordered_faces], proj_v[ordered_faces]], axis=-1)  # (F, 3, 2)

    diffuse_key = np.clip(ordered_normals @ light_key, 0.0, 1.0)
    diffuse_fill = np.clip(ordered_normals @ light_fill, 0.0, 1.0)
    intensity = np.clip(0.26 + 0.56 * diffuse_key + 0.18 * diffuse_fill, 0.15, 0.98)

    base_rgb = np.array([0.42, 0.56, 0.72], dtype=np.float64)
    face_colors = np.column_stack(
        [
            np.clip(base_rgb[0] * intensity + 0.08 * (diffuse_key**3), 0.0, 1.0),
            np.clip(base_rgb[1] * intensity + 0.08 * (diffuse_key**3), 0.0, 1.0),
            np.clip(base_rgb[2] * intensity + 0.08 * (diffuse_key**3), 0.0, 1.0),
            np.ones_like(intensity),
        ]
    )

    with lock:
        dpi = 120
        fig, ax = plt.subplots(figsize=(width_px / dpi, height_px / dpi), dpi=dpi)
        try:
            fig.patch.set_facecolor("#F8FAFC")
            ax.set_facecolor("#F8FAFC")
            collection = PolyCollection(
                polys_2d,
                facecolors=face_colors,
                edgecolors=(0.18, 0.24, 0.32, 0.22),
                linewidths=0.35,
                antialiased=True,
            )
            ax.add_collection(collection)
            u_min, u_max = float(proj_u.min()), float(proj_u.max())
            v_min, v_max = float(proj_v.min()), float(proj_v.max())
            span = max(u_max - u_min, v_max - v_min, 1.0) * 0.60
            u_mid, v_mid = 0.5 * (u_min + u_max), 0.5 * (v_min + v_max)
            ax.set_xlim(u_mid - span, u_mid + span)
            ax.set_ylim(v_mid - span, v_mid + span)
            ax.set_aspect("equal", adjustable="box")
            ax.axis("off")
            if title:
                # Keep ASCII-safe subtitle or configured font without missing-glyph warnings
                ascii_title = "".join(ch for ch in title if ord(ch) < 128).strip()
                if ascii_title:
                    ax.set_title(ascii_title, fontsize=11, color="#1E293B", pad=8)
            fig.tight_layout(pad=0.3)
            fig.savefig(dest, format="png", dpi=dpi, facecolor=fig.get_facecolor())
        finally:
            plt.close(fig)
    return dest


def _step_string(text: str) -> str:
    """Encode string per ISO 10303-21 (ASCII + \\X2\\XXXX\\X0\\ UCS-2 hex for CJK)."""
    out: list[str] = []
    for ch in text:
        code = ord(ch)
        if ch == "'":
            out.append("''")
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= code <= 126:
            out.append(ch)
        elif code <= 0xFFFF:
            out.append(f"\\X2\\{code:04X}\\X0\\")
    return "".join(out) or "CAD_PART"


def export_step(mesh: SolidMesh3D, path: Path, *, part_name: str = "cad_solid") -> Path:
    """Write a deterministic ISO 10303-21 AP214 (.step) solid B-Rep file (`CLOSED_SHELL` + `FACETED_BREP`)."""
    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    safe_name = _step_string(part_name)

    entities: list[str] = []

    def add_ent(expr: str) -> int:
        eid = len(entities) + 1
        entities.append(f"#{eid} = {expr};")
        return eid

    # 1. AP214 Product & Millimetre Geometric Context
    app_ctx = add_ent("APPLICATION_CONTEXT('automotive_design')")
    add_ent(f"APPLICATION_PROTOCOL_DEFINITION('international standard','automotive_design',2000,#{app_ctx})")
    prod_ctx = add_ent(f"PRODUCT_CONTEXT('',#{app_ctx},'mechanical')")
    prod = add_ent(f"PRODUCT('{safe_name}','{safe_name}','',(#{prod_ctx}))")
    pdf_ctx = add_ent(f"PRODUCT_DEFINITION_FORMATION_WITH_SPECIFIED_SOURCE('','',#{prod},.NOT_KNOWN.)")
    pdef_ctx = add_ent(f"PRODUCT_DEFINITION_CONTEXT('part definition',#{app_ctx},'design')")
    pdef = add_ent(f"PRODUCT_DEFINITION('design','',#{pdf_ctx},#{pdef_ctx})")
    pds = add_ent(f"PRODUCT_DEFINITION_SHAPE('','',#{pdef})")

    len_unit = add_ent("( LENGTH_UNIT() NAMED_UNIT(*) SI_UNIT(.MILLI.,.METRE.) )")
    ang_unit = add_ent("( NAMED_UNIT(*) PLANE_ANGLE_UNIT() SI_UNIT($,.RADIAN.) )")
    sol_unit = add_ent("( NAMED_UNIT(*) SOLID_ANGLE_UNIT() SI_UNIT($,.STERADIAN.) )")
    unc = add_ent(f"UNCERTAINTY_MEASURE_WITH_UNIT(LENGTH_MEASURE(1.E-05),#{len_unit},'distance_accuracy_value','confusion accuracy')")
    geom_ctx = add_ent(
        f"( GEOMETRIC_REPRESENTATION_CONTEXT(3) GLOBAL_UNCERTAINTY_ASSIGNED_CONTEXT((#{unc})) "
        f"GLOBAL_UNIT_ASSIGNED_CONTEXT((#{len_unit},#{ang_unit},#{sol_unit})) REPRESENTATION_CONTEXT('Context3D','3D Context') )"
    )

    origin_pt = add_ent("CARTESIAN_POINT('',(0.,0.,0.))")
    dir_z = add_ent("DIRECTION('',(0.,0.,1.))")
    dir_x = add_ent("DIRECTION('',(1.,0.,0.))")
    world_ax = add_ent(f"AXIS2_PLACEMENT_3D('',#{origin_pt},#{dir_z},#{dir_x})")

    # 2. Deduplicated shared topological CARTESIAN_POINT table
    pt_ids: list[int] = []
    for vx, vy, vz in mesh.vertices:
        pt_ids.append(add_ent(f"CARTESIAN_POINT('',({vx:.6f},{vy:.6f},{vz:.6f}))"))

    # 3. Oriented planar faces forming a closed manifold shell
    normals = mesh.face_normals
    verts = mesh.vertices
    face_ids: list[int] = []
    for f_idx, (i0, i1, i2) in enumerate(mesh.faces):
        p0_id = pt_ids[int(i0)]
        p1_id = pt_ids[int(i1)]
        p2_id = pt_ids[int(i2)]
        nx, ny, nz = float(normals[f_idx, 0]), float(normals[f_idx, 1]), float(normals[f_idx, 2])
        edge_vec = verts[int(i1)] - verts[int(i0)]
        e_norm = float(np.linalg.norm(edge_vec))
        if e_norm > 1e-12:
            tx, ty, tz = float(edge_vec[0] / e_norm), float(edge_vec[1] / e_norm), float(edge_vec[2] / e_norm)
        else:
            tx, ty, tz = 1.0, 0.0, 0.0
        n_id = add_ent(f"DIRECTION('',({nx:.6f},{ny:.6f},{nz:.6f}))")
        t_id = add_ent(f"DIRECTION('',({tx:.6f},{ty:.6f},{tz:.6f}))")
        ax_id = add_ent(f"AXIS2_PLACEMENT_3D('',#{p0_id},#{n_id},#{t_id})")
        pln_id = add_ent(f"PLANE('',#{ax_id})")
        loop_id = add_ent(f"POLY_LOOP('',(#{p0_id},#{p1_id},#{p2_id}))")
        bnd_id = add_ent(f"FACE_OUTER_BOUND('',#{loop_id},.T.)")
        face_ids.append(add_ent(f"FACE_SURFACE('',(#{bnd_id}),#{pln_id},.T.)"))

    face_refs = ",".join(f"#{fid}" for fid in face_ids)
    shell_id = add_ent(f"CLOSED_SHELL('',({face_refs}))")
    brep_id = add_ent(f"FACETED_BREP('{safe_name}',#{shell_id})")
    shape_rep = add_ent(f"FACETED_BREP_SHAPE_REPRESENTATION('{safe_name}',(#{brep_id},#{world_ax}),#{geom_ctx})")
    add_ent(f"SHAPE_DEFINITION_REPRESENTATION(#{pds},#{shape_rep})")

    header = [
        "ISO-10303-21;",
        "HEADER;",
        "FILE_DESCRIPTION(('CAD Operations Skill Watertight Solid B-Rep'),'2;1');",
        f"FILE_NAME('{_step_string(dest.name)}','2026-01-01T00:00:00',('cad-operations-skill'),(''),"
        "'cad-operations-skill/modeling3d','cad-operations-skill','');",
        "FILE_SCHEMA(('AUTOMOTIVE_DESIGN { 1 0 10303 214 1 1 1 1 }'));",
        "ENDSEC;",
        "DATA;",
    ]
    footer = [
        "ENDSEC;",
        "END-ISO-10303-21;",
        "",
    ]
    dest.write_text("\n".join(header + entities + footer), encoding="ascii")
    return dest
