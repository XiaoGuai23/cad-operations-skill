"""Pluggable native 3D CAD adapters and AutoCAD 3DSOLID script generator."""

from __future__ import annotations

import importlib.util
from math import cos, pi, sin
from pathlib import Path
import shutil
from typing import Any

from .models import (
    Box3D,
    BoxBoss3D,
    CompoundSolid3D,
    Cylinder3D,
    CylinderBoss3D,
    Flange3D,
    Model3DSpec,
    SteppedShaft3D,
)


def probe_3d_capabilities() -> dict[str, Any]:
    """Read-only probe of built-in and optional external 3D CAD kernels/drivers."""

    has_build123d = importlib.util.find_spec("build123d") is not None
    has_cadquery = importlib.util.find_spec("cadquery") is not None
    has_pywin32 = importlib.util.find_spec("win32com") is not None

    freecad_cmd = shutil.which("FreeCADCmd")
    if freecad_cmd is None:
        for candidate in (
            Path(r"C:\Program Files\FreeCAD 1.0\bin\FreeCADCmd.exe"),
            Path(r"C:\Program Files\FreeCAD 0.21\bin\FreeCADCmd.exe"),
        ):
            if candidate.is_file():
                freecad_cmd = str(candidate)
                break

    sw_root = Path(r"C:\Program Files\SOLIDWORKS Corp")
    sw_installed = sw_root.is_dir() and any(sw_root.glob("**/SLDWORKS.exe"))

    return {
        "builtin_manifold_mesh": {
            "available": True,
            "formats": ["step", "stl", "obj", "glb", "dxf3d", "png_iso"],
            "note": "Zero-external-install deterministic watertight B-Rep/mesh & 3D->2D projection engine.",
        },
        "build123d_brep": {
            "available": has_build123d,
            "formats": ["step", "stl", "brep"] if has_build123d else [],
        },
        "cadquery_brep": {
            "available": has_cadquery,
            "formats": ["step", "stl"] if has_cadquery else [],
        },
        "freecad_headless": {
            "available": freecad_cmd is not None,
            "executable": freecad_cmd,
        },
        "solidworks_com": {
            "available": bool(has_pywin32 and sw_installed),
            "pywin32_installed": has_pywin32,
            "solidworks_detected": sw_installed,
        },
        "autocad_3dsolid_script": {
            "available": True,
            "note": "Generates controlled Core Console .scr scripts for ACIS 3DSOLID creation.",
        },
    }


def _safe_scr_path(path: Path) -> str:
    text = str(Path(path).resolve())
    if any(ch in text for ch in ("\r", "\n", '"')):
        raise ValueError(f"unsafe path character for AutoCAD script: {path}")
    return f'"{text}"'


def generate_autocad_3d_script(spec_3d: Model3DSpec, output_dwg_path: Path) -> str:
    """Generate a deterministic AutoCAD Core Console (.scr) script for native ACIS 3DSOLIDs."""

    dwg_literal = _safe_scr_path(output_dwg_path)
    body = spec_3d.body
    lines = [
        "; Controlled AutoCAD Core Console 3DSOLID script generated by cad-operations-skill",
        "FILEDIA 0",
        "CMDDIA 0",
        "_UNITS 2 4 1 2 0 _N",
        "INSUNITS 4",
        "-LAYER _M SOLID3D _C 7 SOLID3D ",
    ]

    if isinstance(body, Box3D):
        hw, hd = body.width / 2.0, body.depth / 2.0
        lines.append(f"_BOX {-hw:.4f},{-hd:.4f},0 {hw:.4f},{hd:.4f},{body.height:.4f}")
        lines.append("_SETVAR USERS1 _LAST")
        for hx, hy, hd_i in body.through_holes:
            r = hd_i / 2.0
            lines.append(f"_CYLINDER {hx:.4f},{hy:.4f},0 {r:.4f} {body.height:.4f}")
            lines.append("_SUBTRACT _P  _L ")

    elif isinstance(body, Cylinder3D):
        r_out = body.outer_diameter / 2.0
        lines.append(f"_CYLINDER 0,0,0 {r_out:.4f} {body.height:.4f}")
        if body.bore_diameter > 0:
            r_in = body.bore_diameter / 2.0
            lines.append(f"_CYLINDER 0,0,0 {r_in:.4f} {body.height:.4f}")
            lines.append("_SUBTRACT _P  _L ")

    elif isinstance(body, Flange3D):
        r_out = body.outer_diameter / 2.0
        total_h = body.thickness + (body.hub_height if body.hub_height > 0 else 0.0)
        lines.append(f"_CYLINDER 0,0,0 {r_out:.4f} {body.thickness:.4f}")
        if body.hub_height > 0 and body.hub_diameter is not None:
            r_hub = body.hub_diameter / 2.0
            lines.append(f"_CYLINDER 0,0,{body.thickness:.4f} {r_hub:.4f} {body.hub_height:.4f}")
            lines.append("_UNION _ALL ")
        if body.bore_diameter > 0:
            r_bore = body.bore_diameter / 2.0
            lines.append(f"_CYLINDER 0,0,0 {r_bore:.4f} {total_h:.4f}")
            lines.append("_SUBTRACT _P  _L ")
        if body.hole_count > 0 and body.bolt_circle_diameter and body.hole_diameter:
            r_bcd = body.bolt_circle_diameter / 2.0
            r_h = body.hole_diameter / 2.0
            for k in range(body.hole_count):
                ang = 2.0 * pi * k / body.hole_count
                hx, hy = r_bcd * cos(ang), r_bcd * sin(ang)
                lines.append(f"_CYLINDER {hx:.4f},{hy:.4f},0 {r_h:.4f} {body.thickness:.4f}")
                lines.append("_SUBTRACT _P  _L ")

    elif isinstance(body, SteppedShaft3D):
        z = 0.0
        for idx, (length, dia) in enumerate(body.steps):
            lines.append(f"_CYLINDER 0,0,{z:.4f} {dia/2.0:.4f} {length:.4f}")
            if idx > 0:
                lines.append("_UNION _ALL ")
            z += length
        if body.bore_diameter > 0:
            lines.append(f"_CYLINDER 0,0,0 {body.bore_diameter/2.0:.4f} {z:.4f}")
            lines.append("_SUBTRACT _P  _L ")

    elif isinstance(body, CompoundSolid3D):
        h_b = body.base_height
        if body.base_shape == "box":
            hw, hd = body.width / 2.0, body.depth / 2.0
            lines.append(f"_BOX {-hw:.4f},{-hd:.4f},0 {hw:.4f},{hd:.4f},{h_b:.4f}")
        else:
            lines.append(f"_CYLINDER 0,0,0 {body.outer_diameter/2.0:.4f} {h_b:.4f}")
        for boss in body.bosses:
            if isinstance(boss, CylinderBoss3D):
                lines.append(f"_CYLINDER {boss.x:.4f},{boss.y:.4f},{h_b:.4f} {boss.diameter/2.0:.4f} {boss.height:.4f}")
                lines.append("_UNION _ALL ")
                if boss.bore_diameter > 0:
                    lines.append(f"_CYLINDER {boss.x:.4f},{boss.y:.4f},0 {boss.bore_diameter/2.0:.4f} {h_b + boss.height:.4f}")
                    lines.append("_SUBTRACT _P  _L ")
            else:
                assert isinstance(boss, BoxBoss3D)
                bhw, bhd = boss.width / 2.0, boss.depth / 2.0
                lines.append(
                    f"_BOX {boss.x - bhw:.4f},{boss.y - bhd:.4f},{h_b:.4f} "
                    f"{boss.x + bhw:.4f},{boss.y + bhd:.4f},{h_b + boss.height:.4f}"
                )
                lines.append("_UNION _ALL ")
        for hx, hy, hd_i in body.through_holes:
            lines.append(f"_CYLINDER {hx:.4f},{hy:.4f},0 {hd_i/2.0:.4f} {h_b:.4f}")
            lines.append("_SUBTRACT _P  _L ")
        for cb in body.counterbores:
            z_step = h_b - cb.cbore_depth
            lines.append(f"_CYLINDER {cb.x:.4f},{cb.y:.4f},0 {cb.through_diameter/2.0:.4f} {h_b:.4f}")
            lines.append("_SUBTRACT _P  _L ")
            lines.append(f"_CYLINDER {cb.x:.4f},{cb.y:.4f},{z_step:.4f} {cb.cbore_diameter/2.0:.4f} {cb.cbore_depth:.4f}")
            lines.append("_SUBTRACT _P  _L ")

    else:
        # Extruded polygon / slotted bracket note: 3D DXF MESH is already generated alongside
        lines.append("; Complex contour extruded as verified 3D MESH in model3d.dxf")

    lines.extend(
        [
            "_VPOINT 1,-1,1",
            "_ZOOM _E",
            f"_SAVEAS 2018 {dwg_literal}",
            "_QUIT _Y",
        ]
    )
    return "\n".join(lines) + "\n"
